import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import {
  cp,
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  rm,
  symlink,
} from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";
import { Effect, Schema } from "effect";

export class WebBuildError extends Schema.TaggedError<WebBuildError>()(
  "WebBuildError",
  {},
) {}
export interface WebAssets {
  html: string;
  policy: string;
  files: ReadonlyMap<string, { body: Uint8Array; type: string }>;
}

/** The app release already exports src/ and root dependencies. Build once on
 * first authenticated use, off the messaging startup path. All generated bytes
 * live outside the sealed release; the builder receives no runtime credentials. */
export const buildWebAssets = Effect.fn("june.web.build")(function* () {
  return yield* Effect.tryPromise({
    try: async (signal) => {
      const workspace = await mkdtemp(join(tmpdir(), "june-web-"));
      try {
        const source = fileURLToPath(new URL("./ui", import.meta.url));
        // Kit's generated tsconfig and Vite's nested config loader both need a
        // writable workspace. Copy source only, never stale generated files.
        await cp(source, workspace, {
          recursive: true,
          filter: (path) =>
            ![".svelte-kit", "node_modules"].some(
              (name) =>
                path === join(source, name) ||
                path.startsWith(`${join(source, name)}/`),
            ),
        });
        // The directory itself must be writable for Vite's .vite-temp. Only
        // dependency entries point at the sealed release, not node_modules.
        await mkdir(join(workspace, "node_modules"));
        for (const name of ["@sveltejs", "svelte", "vite", "typescript"]) {
          await symlink(
            fileURLToPath(
              new URL(`../../node_modules/${name}`, import.meta.url),
            ),
            join(workspace, "node_modules", name),
            "dir",
          );
        }
        const vite = join(
          dirname(createRequire(import.meta.url).resolve("vite/package.json")),
          "bin/vite.js",
        );
        await promisify(execFile)(
          process.execPath,
          [vite, "build", "--configLoader", "native"],
          {
            cwd: workspace,
            env: {
              PATH: process.env.PATH,
              NODE_ENV: "production",
            },
            signal,
            timeout: 60_000,
            maxBuffer: 2_000_000,
          },
        );
        const output = join(workspace, ".svelte-kit/web");
        const html = await readFile(join(output, "pages/index.html"), "utf8");
        const hashes = [
          ...html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g),
        ].map(
          (match) =>
            `'sha256-${createHash("sha256")
              .update(match[1] ?? "")
              .digest("base64")}'`,
        );
        const files = new Map<string, { body: Uint8Array; type: string }>();
        for (const file of await readdir(join(output, "client"), {
          recursive: true,
          withFileTypes: true,
        })) {
          if (!file.isFile()) continue;
          const path = join(file.parentPath, file.name);
          const url = `/app/${path.slice(join(output, "client").length + 1)}`;
          const type = file.name.endsWith(".js")
            ? "text/javascript; charset=utf-8"
            : file.name.endsWith(".css")
              ? "text/css; charset=utf-8"
              : file.name.endsWith(".json")
                ? "application/json"
                : "application/octet-stream";
          files.set(url, { body: new Uint8Array(await readFile(path)), type });
        }
        return {
          html,
          files,
          policy: `default-src 'none'; script-src 'self' ${hashes.join(" ")}; style-src 'self'; connect-src 'self'; img-src 'self'; base-uri 'none'; frame-ancestors 'none'; form-action 'self'`,
        };
      } finally {
        await rm(workspace, { recursive: true, force: true });
      }
    },
    catch: () => new WebBuildError(),
  });
});
